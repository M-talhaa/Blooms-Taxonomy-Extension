#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""SCS weight sensitivity of the model selection (thin wrapper around robustness.py).

For every weight setting (500 joint draws, numpy default_rng(13), each weight times
U(0.5, 1.5) in the order wD, wM, wT, wC, wE; and each weight alone x0.5, x0.75, x1.25, x1.5)
robustness.analysis_scs_weights re-aggregates SCS from the stored components of
structural_scan_components.csv, recomputes the penalized objective (bands and penalties
unchanged), re-selects each family's best configuration, pulls that configuration's matched
supervised numbers (results/selection/supervised_grid_per_seed.csv) and applies the proposed
selection rule, the structural-only rule and the round-2 two-stage rule. No retraining.

This file only writes the short summary scs_sensitivity.md; the full per-setting table is
results/selection/robustness_scs_weights.csv, written by robustness.py.

Usage (from the repository root):
  python -I -B revision_pipeline/scs_sensitivity.py
  python -I -B revision_pipeline/scs_sensitivity.py --components <dir>/structural_scan_components.csv
"""
import argparse
import os
import sys
from collections import Counter

PIPE = os.path.dirname(os.path.abspath(__file__))
if PIPE not in sys.path:
    sys.path.insert(0, PIPE)
import robustness as rb  # noqa: E402
import select_model as sm  # noqa: E402


def summarize(D, components):
    J = D[D.setting.str.startswith("joint")]
    S = D[D.setting.str.startswith("single")]
    b = D[D.setting == "baseline"].iloc[0]
    L = ["# SCS weight sensitivity (generated by scs_sensitivity.py through robustness.py; do not edit by hand)", ""]
    rel = os.path.relpath(os.path.abspath(components), sm.REPO).replace(os.sep, "/")
    L.append(f"Components: `{rel}`. Selection rule: `{sm.SELECTION_RULE}` (select_model.py). Supervised numbers are "
             "matched to the configuration each family selects under each weight setting.")
    L.append("")
    L.append(f"Baseline weights {sm.BASE_WEIGHTS}: proposed rule {b['proposed_A_winner']} ({b['proposed_A_score']:.6f}; "
             f"runner-up {b['proposed_A_runner_up']}); structural-only rule {b['A_structural_winner']}; round-2 "
             f"two-stage rule (held-out seed 13) {b['A_seed13_winner']}.")
    L.append("")
    L.append(f"## {len(J)} joint draws")
    L.append("")
    for col, lab in [("proposed_A_winner", "Proposed rule (one-vs-rest families)"),
                     ("A_structural_winner", "Structural-only rule (one-vs-rest families)"),
                     ("B_structural_winner", "Structural-only rule (Legacy kNN included)"),
                     ("A_seed13_winner", "Round-2 two-stage rule, matched inputs, held-out seed 13"),
                     ("proposed_B_winner", "Proposed rule with Legacy kNN admitted (evaluation-only)")]:
        L.append(f"- {lab}: " + rb._counts(J[col]))
    L.append("- Floor-passing one-vs-rest families per draw (absolute floor 0.5, on a scale that moves with the "
             "weights): " + ", ".join(f"{int(k)}: {v}" for k, v in sorted(Counter(J["A_n_floor"]).items())))
    full = J[J.A_n_floor == J.A_n_floor.max()]
    L.append(f"- Draws with all {int(J.A_n_floor.max())} families above the floor ({len(full)}): proposed rule "
             + rb._counts(full["proposed_A_winner"]))
    L.append("")
    L.append(f"## {len(S)} single-weight settings")
    L.append("")
    L.append(sm.md_table(S, ["setting", "proposed_A_winner", "proposed_A_score", "proposed_A_runner_up",
                             "A_structural_winner", "A_seed13_winner"]))
    L.append("")
    L.append("Full per-setting values: results/selection/robustness_scs_weights.csv (robustness.py).")
    txt = "\n".join(L)
    for bad in (chr(0x2013), chr(0x2014)):
        assert bad not in txt
    return txt


def main():
    ap = argparse.ArgumentParser(description="SCS weight sensitivity of the model selection")
    ap.add_argument("--components", default=sm.SCAN_CSV, help="structural_scan_components.csv")
    ap.add_argument("--sel-dir", default=sm.SEL_DIR, help="folder with supervised_grid_per_seed.csv")
    ap.add_argument("--out", default=os.path.join(PIPE, "scs_sensitivity.md"))
    ap.add_argument("--draws", type=int, default=rb.N_DRAWS)
    args = ap.parse_args()
    ctx = rb.Ctx(args.components, args.sel_dir)
    D, _ = rb.analysis_scs_weights(ctx, args.draws)
    txt = summarize(D, args.components)
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(txt + "\n")
    print(txt)
    print(f"saved: {args.out}")


if __name__ == "__main__":
    main()
